#!/usr/bin/env python3
"""Generate the two result figures of the manuscript from the results files.

  fig_traces.tex   (Fig. fig:traces)   <- results/T35_day_traces.csv
  fig_timestep.tex (Fig. fig:timestep) <- results/T2v3_timestep.csv
  fig_ladder.tex   (Fig. fig:ladder)   <- results/T1v3_heldout.csv, rbrl_ppo5_v3_<c>.csv,
                                          T21v3_<c>.csv, T21v3_pers_<c>.csv, T17v3_<c>.csv
                                          (checked cell by cell against tab:main in main.tex)

Standard library only (csv).  Every number printed in the two captions is read
from the CSVs here; nothing is typed by hand.  Run:

    python3 make_result_figs.py [RESULTS_DIR]

RESULTS_DIR defaults to ../results relative to this script (the repository's
results/ when run from paper/).  The output files are written next to this script.

Conventions for the traces: `hour` is the start of the 15-min step (0 = 00:00
of day 1 of the window; day 0 is warm-up and is not in the file), `u_*` is the
command held over [hour, hour+0.25) and `T_*` is the room temperature at the
end of the step, so it is drawn at hour+0.25.  An on-command is a 0->1
transition of `u`; the first step of the file has u = 0 for every arm, so no
command is lost at the window cut.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "results")
HEADER = ("%% GENERATED by make_result_figs.py from results/T35_day_traces.csv / "
          "T2v3_timestep.csv; do not edit\n")

CITY = {"riyadh": "Riyadh", "jeddah": "Jeddah", "taif": "Taif"}

# Okabe-Ito colour-blind-safe palette, one meaning per arm across Figs traces/ladder:
#   THERM black, guard hysteresis sky, RBRL green, TUNED blue, MPC 24 h vermillion
#   (persistence forecast: vermillion hatching), bound / clairvoyant bracket purple.
# In fig:timestep colour marks the city instead (black / green / sky; none of the
# arms drawn there), and line style marks the arm.  Lightness differs between the
# colours used together, and hatching separates the two MPC rungs, so the figures
# also read in greyscale print.
COLDEF = ("\\definecolor{oiBlue}{HTML}{0072B2}\\definecolor{oiOrange}{HTML}{E69F00}"
          "\\definecolor{oiGreen}{HTML}{009E73}\\definecolor{oiVerm}{HTML}{D55E00}\n"
          "\\definecolor{oiSky}{HTML}{56B4E9}\\definecolor{oiPurple}{HTML}{CC79A7}\n")


def fmt(x, nd=1):
    """Signed-aware LaTeX number with a true minus sign."""
    s = f"{x:.{nd}f}"
    if s.startswith("-"):
        s = "-" + s[1:]
    return s


