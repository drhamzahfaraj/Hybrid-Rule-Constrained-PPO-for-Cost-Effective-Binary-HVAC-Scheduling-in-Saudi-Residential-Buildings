#!/usr/bin/env python3
"""Generate the two result figures of the manuscript from the results files.

  fig_traces.tex   (Fig. fig:traces)   <- results/T35_day_traces.csv
  fig_timestep.tex (Fig. fig:timestep) <- results/T2v3_timestep.csv
  fig_ladder.tex   (Fig. fig:ladder)   <- results/T1v3_heldout.csv, rbrl_ppo5_v3_<c>.csv,
                                          T21v3_<c>.csv, T21v3_pers_<c>.csv, T17v3_<c>.csv
                                          (checked cell by cell against tab:main in main.tex)

Standard library only (csv).  Every number printed in the two captions is read
from the CSVs here; nothing is typed by hand.  Run:

    python3 make_result_figs.py [RESULTS_DIR]

RESULTS_DIR defaults to ../results relative to this script (the repository's
results/ when run from paper/).  The output files are written next to this script.

Conventions for the traces: `hour` is the start of the 15-min step (0 = 00:00
of day 1 of the window; day 0 is warm-up and is not in the file), `u_*` is the
command held over [hour, hour+0.25) and `T_*` is the room temperature at the
end of the step, so it is drawn at hour+0.25.  An on-command is a 0->1
transition of `u`; the first step of the file has u = 0 for every arm, so no
command is lost at the window cut.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "results")
HEADER = ("%% GENERATED by make_result_figs.py from results/T35_day_traces.csv / "
          "T2v3_timestep.csv; do not edit\n")

CITY = {"riyadh": "Riyadh", "jeddah": "Jeddah", "taif": "Taif"}


def fmt(x, nd=1):
    """Signed-aware LaTeX number with a true minus sign."""
    s = f"{x:.{nd}f}"
    if s.startswith("-"):
        s = "-" + s[1:]
    return s


# ---------------------------------------------------------------- Figure A
def traces():
    rows = list(csv.DictReader(open(os.path.join(RES, "T35_day_traces.csv"))))
    assert len(rows) == 192, len(rows)
    rows.sort(key=lambda r: float(r["hour"]))
    city = {r["city"] for r in rows}
    start = {r["start_day"] for r in rows}
    assert len(city) == 1 and len(start) == 1
    city, start = CITY[city.pop()], int(start.pop())
    lo = {float(r["lo"]) for r in rows if r["occupied"] == "1"}
    hi = {float(r["hi"]) for r in rows if r["occupied"] == "1"}
    assert len(lo) == 1 and len(hi) == 1
    lo, hi = lo.pop(), hi.pop()
    assert all(r["occupied"] == "1" for r in rows), "band shading assumes all occupied"
    h = [float(r["hour"]) for r in rows]
    dt = h[1] - h[0]
    hend = h[-1] + dt
    arms = [("therm", "THERM"), ("tuned", "TUNED"), ("mpc", r"MPC $24\,$h")]
    T = {a: [float(r["T_" + a]) for r in rows] for a, _ in arms}
    U = {a: [int(float(r["u_" + a])) for r in rows] for a, _ in arms}
    tout = [float(r["t_out"]) for r in rows]
    on2 = {}
    for a, _ in arms:
        assert U[a][0] == 0
        on2[a] = sum(1 for i in range(1, len(rows)) if U[a][i] == 1 and U[a][i - 1] == 0)
    week = {a: {int(r["week_on_" + a]) for r in rows} for a, _ in arms}
    for a in week:
        assert len(week[a]) == 1
        week[a] = week[a].pop()
    t_on = {r["tuned_on"] for r in rows}.pop()
    t_off = {r["tuned_off"] for r in rows}.pop()
    tmin_out, tmax_out = min(tout), max(tout)

    style = {
        "therm": "black, thin",
        "tuned": "blue!75!black, thick, dashed",
        "mpc": "orange!85!black, thick, dash dot",
    }
    fill = {"therm": "black!70", "tuned": "blue!75!black", "mpc": "orange!85!black"}

    def coords(xs, ys):
        return "".join(f"({x:.2f},{y:.3f})" for x, y in zip(xs, ys))

    out = [HEADER,
           "%% Selection: hottest held-out Riyadh week (window start_day %d), days 1-2,\n" % start,
           "%% fixed before the traces were drawn; day 0 is warm-up and is not shown.\n",
           "\\begin{figure*}[t]\n\\centering\n\\begin{tikzpicture}\n"]
    out.append(
        "\\begin{axis}[\n"
        "  width=0.92\\textwidth, height=3.3cm,\n"
        f"  xmin=0, xmax={hend:g}, ymin={lo - 0.25:g}, ymax={hi + 0.25:g},\n"
        "  xtick={0,6,...,48}, xticklabels={,,,,,,,,},\n"
        f"  ytick={{{lo:g},22.5,23,23.5,{hi:g}}},\n"
        "  ylabel={Room ($^\\circ$C)},\n"
        "  grid=major, grid style={dotted,gray!40},\n"
        "  tick label style={font=\\scriptsize}, label style={font=\\small},\n"
        "  legend style={font=\\scriptsize, at={(0.5,1.02)}, anchor=south,\n"
        "    legend columns=5, draw=none, fill=none, /tikz/every even column/.append style={column sep=6pt}},\n"
        "  name=main, axis y line*=left,\n"
        "]\n")
    out.append(f"\\addplot[fill=green!10,draw=none,area legend] coordinates{{(0,{lo:g})(0,{hi:g})({hend:g},{hi:g})({hend:g},{lo:g})}}\\closedcycle;\n")
    out.append("\\addlegendentry{occupied band}\n")
    xs = [x + dt for x in h]
    for a, name in arms:
        out.append(f"\\addplot[{style[a]}] coordinates{{{coords(xs, T[a])}}};\n")
        out.append(f"\\addlegendentry{{{name}}}\n")
    out.append("\\addlegendimage{gray!60, thin, densely dotted}\\addlegendentry{outdoor (right axis)}\n")
    out.append("\\end{axis}\n")
    # outdoor temperature on a secondary axis (light, behind)
    out.append(
        "\\begin{axis}[\n"
        "  width=0.92\\textwidth, height=3.3cm, at={(main.south west)}, anchor=south west,\n"
        f"  xmin=0, xmax={hend:g}, ymin=28, ymax=46,\n"
        "  axis y line*=right, axis x line=none,\n"
        "  ytick={30,35,40,45}, ylabel={Outdoor ($^\\circ$C)},\n"
        "  tick label style={font=\\scriptsize, gray}, label style={font=\\small, gray},\n"
        "]\n")
    out.append(f"\\addplot[gray!60, thin, densely dotted] coordinates{{{coords(h, tout)}}};\n")
    out.append("\\end{axis}\n")
    # on/off strips
    out.append(
        "\\begin{axis}[\n"
        "  at={(main.south west)}, anchor=north west, yshift=-2mm,\n"
        f"  width=0.92\\textwidth, height=2.7cm, xmin=0, xmax={hend:g}, ymin=0, ymax=3,\n"
        "  xtick={0,6,...,48}, xlabel={Hour from the start of day 1},\n"
        "  ytick={0.5,1.5,2.5}, yticklabels={MPC $24\\,$h,TUNED,THERM},\n"
        "  y tick style={draw=none}, axis y line*=left,\n"
        "  grid=none, xmajorgrids, grid style={dotted,gray!40},\n"
        "  tick label style={font=\\scriptsize}, label style={font=\\small},\n"
        "]\n")
    for row, (a, _) in zip([2, 1, 0], arms):
        out.append(f"\\addplot[draw=gray!50,thin] coordinates{{(0,{row + 0.5})({hend:g},{row + 0.5})}};\n")
        i = 0
        while i < len(rows):
            if U[a][i] == 1:
                j = i
                while j + 1 < len(rows) and U[a][j + 1] == 1:
                    j += 1
                x0, x1 = h[i], h[j] + dt
                out.append(f"\\fill[{fill[a]}] (axis cs:{x0:g},{row + 0.15}) rectangle (axis cs:{x1:g},{row + 0.85});\n")
                i = j + 1
            else:
                i += 1
    out.append("\\end{axis}\n\\end{tikzpicture}\n")
    # the selected week's per-window savings (TUNED; 24 h MPC, perfect forecast)
    pw = [r for r in csv.DictReader(open(os.path.join(RES, "T1v3_perwindow.csv")))
          if r["tariff"] == "inforce" and r["arm"] == "TUNED" and r["city"] == "riyadh"]
    sw_t = {int(r["window"]): float(r["s_w"]) for r in pw}
    assert len(sw_t) == 7 and start in sw_t
    assert sw_t[start] == min(sw_t.values()), "selected week is TUNED's lowest"
    pm = [r for r in csv.DictReader(open(os.path.join(RES, "T21v3_riyadh_perwindow.csv")))
          if float(r["horizon_h"]) == 24.0 and r["forecast"] == "perfect"]
    sw_m = {int(r["window"]): float(r["s_w"]) for r in pm}
    marg = {w: sw_m[w] - sw_t[w] for w in sw_t}
    cap = (
        f"\\caption{{A two-day operating trace: the held-out {city} week with the "
        "highest mean outdoor temperature, days~1--2, fixed before the traces were "
        "drawn (day~0 is not shown). It is the held-out week in which TUNED's saving is "
        f"lowest (${fmt(sw_t[start])}\\%$); the MPC margin over it there is "
        f"${fmt(marg[start])}$ points. Upper: room temperature at the end of each "
        "$15$-min step under THERM (unshifted), TUNED and the $24\\,$h MPC (perfect "
        f"forecast), with the occupied band $[{lo:g},{hi:g}]\\,^\\circ$C shaded and "
        f"the outdoor temperature ({fmt(tmin_out)}--{fmt(tmax_out)}$\\,^\\circ$C) on "
        "the right axis. Lower: cooling command (filled: on). THERM, TUNED and MPC issue "
        f"{on2['therm']}, {on2['tuned']} and {on2['mpc']} on-commands over the two days and "
        f"{week['therm']}, {week['tuned']} and {week['mpc']} over the week. TUNED's switch "
        f"points ({t_on}/{t_off}$\\,^\\circ$C) widen THERM's $1\\,^\\circ$C deadband, so "
        "TUNED cycles less; MPC uses the full band "
        f"({fmt(min(T['mpc']),2)}--{fmt(max(T['mpc']),2)}$\\,^\\circ$C).}}\n")
    out.append(cap)
    out.append("\\label{fig:traces}\n\\end{figure*}\n")
    open(os.path.join(HERE, "fig_traces.tex"), "w").write("".join(out))
    return on2, week


